class I18N:
    def __init__(self, lang_choice: str = "English"):
        self.lang_choice = lang_choice if lang_choice in LANG_CHOICES else "English"

    @property
    def code(self) -> str:
        return LANG_CODE.get(self.lang_choice, "en")

    def tr(self, key: str) -> str:
        return UI_STR.get(self.code, UI_STR["en"]).get(key, UI_STR["en"].get(key, key))

    def tt(self, key: str) -> str:
        return TT_STR.get(self.code, TT_STR.get("en", {})).get(key, "")
